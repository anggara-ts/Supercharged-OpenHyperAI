-- bots/lib/systems/lane_tower_rules.lua: laning next to an enemy tower and the aggro tricks' results (#71).
local T = ...

local function rules()
	T.stub.reset({ hero = "npc_dota_hero_zuus" })
	return require(GetScriptDirectory() .. "/lib/systems/lane_tower_rules")
end

T.test("tower reach: 700 from npc_units.txt plus both radii", function()
	local R = rules()
	-- Game 040: [SHy-PUSH] wait-outside-tower range=868 for a hero (700 + 168 of radii).
	T.eq(R.Reach(700, 144, 24), 868, "a hero")
	T.eq(R.Reach(nil, 144, 24), 868, "no range read: 700")
	T.eq(R.Reach(0, nil, nil), 700, "nothing read")
	T.ok(R.InZone(968, 868), "reach + 100 is still in the zone")
	T.ok(not R.InZone(969, 868), "past the margin")
end)

T.test("tower exit: game 071, Largo inside Dire's top T1 range", function()
	local R = rules()
	-- t=333: towerOnMe=false (the tower on our creeps, holders=6), hp 0.67, Phantom Assassin near.
	T.eq(R.ExitReason(false, true, 0.67, 150), "hp", "67% HP with the tower on a creep")
	-- t=347: hp 0.58.
	T.eq(R.ExitReason(false, true, 0.58, 400), "hp", "58% HP")
	T.eq(R.ExitReason(true, false, 0.95, 900), "tower-on-me", "the tower shoots the bot")
	T.eq(R.ExitReason(false, false, 0.95, 900), "tower-free", "the tower shoots nothing or a hero")
end)

T.test("tower exit: a healthy bot may stay while the tower shoots a creep and no hero reaches it", function()
	local R = rules()
	T.eq(R.ExitReason(false, true, 0.7, 201), nil, "70% HP, the nearest hero 201 past his range")
	T.eq(R.ExitReason(false, true, 0.9, 200), "hero-reach", "a hero within his range + 200")
	T.eq(R.ExitReason(false, true, 0.9, -50), "hero-reach", "a hero already in range")
	T.eq(R.ExitReason(true, false, 0.2, nil), nil, "no enemy hero near: the other laning rules decide")
end)

T.test("tower escape: retreat over evasive when hit in the zone under 60% HP", function()
	local R = rules()
	-- Game 071 t=347-353: Largo 0.58, evasive active, Phantom Assassin hitting him in the T1 range.
	T.eq(R.TowerEscape(true, false, true, 0.58, true), "start", "Largo")
	T.eq(R.TowerEscape(true, false, true, 0.58, false), nil, "not hit")
	T.eq(R.TowerEscape(true, false, true, 0.6, true), nil, "60% is not under 60%")
	T.eq(R.TowerEscape(true, false, false, 0.3, true), nil, "outside the zone: OverEvasiveDesire decides")
	T.eq(R.TowerEscape(false, true, true, 0.5, false), "hold", "held while still in the zone")
	T.eq(R.TowerEscape(false, true, false, 0.5, true), nil, "out of the zone: the hold ends")
	T.eq(R.TowerEscape(false, false, true, 0.5, true), nil, "no start outside evasive")
end)

T.test("glyph leave: outside push, walk out unless the unit inside dies first", function()
	local R = rules()
	-- Game 092: attack mode under a Glyphed T3. The deflect was skipped and push's walk-out never ran.
	T.eq(R.GlyphLeave(false, true, false, false), "leave", "in the tower, no unit to finish")
	T.eq(R.GlyphLeave(false, true, true, false), "leave", "the unit inside does not die first")
	T.eq(R.GlyphLeave(false, false, true, false), "leave", "outside, but the attack would go in")
	T.eq(R.GlyphLeave(false, true, true, true), "finish", "the unit inside dies first")
	T.eq(R.GlyphLeave(false, false, true, true), "finish", "outside, and the unit dies first")
	T.eq(R.GlyphLeave(false, false, false, false), nil, "outside, and not attacking into the tower")
	T.eq(R.GlyphLeave(true, true, true, false), nil, "push mode walks out itself")
end)

T.test("glyph leave: dies first only when both times are known and the target's is shorter", function()
	local R = rules()
	T.eq(R.SecondsUntilDead(200, 100), 2, "200 health at 100 damage a second")
	T.eq(R.SecondsUntilDead(0, 100), 0, "already dead")
	T.eq(R.SecondsUntilDead(200, 0), math.huge, "no damage: does not die")
	T.eq(R.SecondsUntilDead(200, -5), math.huge, "healing is not a death")
	T.eq(R.SecondsUntilDead(200, nil), nil, "unknown damage")
	T.eq(R.SecondsUntilDead(nil, 100), nil, "unknown health")
	T.ok(R.DiesFirst(1, 3), "target in 1s, bot in 3s")
	T.ok(not R.DiesFirst(3, 1), "the bot dies first")
	T.ok(not R.DiesFirst(2, 2), "the same time is not first")
	T.ok(not R.DiesFirst(nil, 1), "unknown target time")
	T.ok(not R.DiesFirst(1, nil), "unknown bot time")
	T.ok(R.DiesFirst(1, math.huge), "the bot does not die to the tower")
	T.ok(not R.DiesFirst(math.huge, math.huge), "neither dies")
end)

T.test("tower-deflect result: every attempt ends in one of four results", function()
	local R = rules()
	T.eq(R.DeflectResult(true, true, 500, 868, true), "died", "died first")
	T.eq(R.DeflectResult(false, false, 0, 0, false), "left-range", "the tower is gone")
	T.eq(R.DeflectResult(false, true, 900, 868, true), "left-range", "out of reach")
	T.eq(R.DeflectResult(false, true, 600, 868, true), "still-on-me", "still the target")
	T.eq(R.DeflectResult(false, true, 600, 868, false), "switched", "the tower changed target")
end)

T.test("pull bait: the nearest hero within 1000, else the first one", function()
	local R = rules()
	-- Game 071: Undying's bait (Puck) was 7800-8200 away in every pull.
	T.eq(R.PickBait({ 7947, 900, 640 }), 3, "nearest near one")
	T.eq(R.PickBait({ 1000, 7947 }), 1, "1000 counts as near")
	T.eq(R.PickBait({ 15048, 8178 }), 1, "no near one: the first, as before")
	T.eq(R.PickBait({}), nil, "none visible")
	T.eq(R.PickBait(nil), nil, "no list")
end)
